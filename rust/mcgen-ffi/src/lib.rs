/// Evaluate the loaded density graph at one world position.
///
/// This is the raw, unchunked reading — the same one the per-route parity probes compare
/// against — so it is useful for asking "what does the engine think the density is here?"
/// without generating anything.
///
/// # Safety
/// `world` must be live and `out_density` writable.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_density(
    world: *const McGenWorld,
    x: f64,
    y: f64,
    z: f64,
    out_density: *mut f64,
) -> i32 {
    guard("mcgen_world_density", || {
        if world.is_null() || out_density.is_null() {
            set_error("world or out_density was null");
            return MCGEN_ERR_NULL;
        }
        let world = unsafe { &*world };
        let d = world.density.compute(&world.noises, x, y, z);
        unsafe { *out_density = d };
        MCGEN_OK
    })
}

/// Fill one chunk the way a `NoiseChunk` does, writing one byte per block: 1 for stone, 0 for
/// air. `out` must hold exactly `16*16*384` bytes, ordered `x + 16*(z + 16*y)`.
///
/// # Safety
/// `world` must be live; `out` writable for `BLOCKS_PER_CHUNK` bytes.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_fill_chunk(
    world: *const McGenWorld,
    chunk_x: i32,
    chunk_z: i32,
    out: *mut u8,
) -> i32 {
    guard("mcgen_world_fill_chunk", || {
        if world.is_null() || out.is_null() {
            set_error("world or out was null");
            return MCGEN_ERR_NULL;
        }
        let world = unsafe { &*world };
        let wg = WorldGen {
            density: &world.density,
            noises: &world.noises,
        };
        let buf = unsafe { std::slice::from_raw_parts_mut(out, BLOCKS_PER_CHUNK) };
        wg.fill_chunk_chunked(chunk_x, chunk_z, buf);
        MCGEN_OK
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::ptr;

    #[test]
    fn abi_version_is_exposed() {
        assert_eq!(mcgen_abi_version(), MCGEN_ABI_VERSION);
    }

    #[test]
    fn create_fill_and_destroy_round_trip() {
        let mut world: *mut McGenWorld = ptr::null_mut();
        assert_eq!(unsafe { mcgen_world_create(42, &mut world) }, MCGEN_OK);
        assert!(!world.is_null());

        let n = 2i32;
        let len = (n * n) as usize * BLOCKS_PER_CHUNK;
        let mut buf = vec![0u8; len];

        assert_eq!(
            unsafe { mcgen_world_fill_region(world, 0, 0, n, buf.as_mut_ptr(), len) },
            MCGEN_OK
        );
        // Something was generated, and it is not all air.
        assert!(buf.iter().any(|&b| b != 0), "region came out empty");

        let mut hash = 0u64;
        assert_eq!(
            unsafe { mcgen_world_fingerprint(world, 0, 0, n, &mut hash) },
            MCGEN_OK
        );
        assert_eq!(hash, fnv1a_bytes(&buf), "fingerprint must match the buffer");

        unsafe { mcgen_world_destroy(world) };
    }

    #[test]
    fn determinism_across_independent_worlds() {
        let mut a: *mut McGenWorld = ptr::null_mut();
        let mut b: *mut McGenWorld = ptr::null_mut();
        unsafe {
            mcgen_world_create(1234, &mut a);
            mcgen_world_create(1234, &mut b);
            let mut ha = 0u64;
            let mut hb = 0u64;
            mcgen_world_fingerprint(a, 0, 0, 3, &mut ha);
            mcgen_world_fingerprint(b, 0, 0, 3, &mut hb);
            assert_eq!(ha, hb, "same seed must give the same world");
            mcgen_world_destroy(a);
            mcgen_world_destroy(b);
        }
    }

    #[test]
    fn different_seeds_give_different_worlds() {
        let mut a: *mut McGenWorld = ptr::null_mut();
        let mut b: *mut McGenWorld = ptr::null_mut();
        unsafe {
            mcgen_world_create(1, &mut a);
            mcgen_world_create(2, &mut b);
            let mut ha = 0u64;
            let mut hb = 0u64;
            mcgen_world_fingerprint(a, 0, 0, 2, &mut ha);
            mcgen_world_fingerprint(b, 0, 0, 2, &mut hb);
            assert_ne!(ha, hb, "different seeds must give different worlds");
            mcgen_world_destroy(a);
            mcgen_world_destroy(b);
        }
    }

    #[test]
    fn serial_and_parallel_agree() {
        let mut world: *mut McGenWorld = ptr::null_mut();
        unsafe {
            assert_eq!(mcgen_world_create(7, &mut world), MCGEN_OK);
            let n = 3i32;
            let len = (n * n) as usize * BLOCKS_PER_CHUNK;
            let mut par = vec![0u8; len];
            let mut ser = vec![0u8; len];
            assert_eq!(
                mcgen_world_fill_region(world, 0, 0, n, par.as_mut_ptr(), len),
                MCGEN_OK
            );
            assert_eq!(
                mcgen_world_fill_region_serial(world, 0, 0, n, ser.as_mut_ptr(), len),
                MCGEN_OK
            );
            assert_eq!(par, ser, "serial and parallel paths must agree");
            mcgen_world_destroy(world);
        }
    }

    #[test]
    fn bad_arguments_are_rejected_not_ignored() {
        let mut world: *mut McGenWorld = ptr::null_mut();
        unsafe { mcgen_world_create(1, &mut world) };

        let mut buf = vec![0u8; BLOCKS_PER_CHUNK];
        // Wrong length must be caught, not written past.
        let rc = unsafe {
            mcgen_world_fill_region(world, 0, 0, 4, buf.as_mut_ptr(), buf.len())
        };
        assert_eq!(rc, MCGEN_ERR_LEN);

        // Null world must be caught.
        let rc = unsafe {
            mcgen_world_fill_region(ptr::null(), 0, 0, 1, buf.as_mut_ptr(), buf.len())
        };
        assert_eq!(rc, MCGEN_ERR_NULL);

        // Non-positive chunk count must be caught.
        let rc =
            unsafe { mcgen_world_fill_region(world, 0, 0, 0, buf.as_mut_ptr(), buf.len()) };
        assert_eq!(rc, MCGEN_ERR_LEN);

        // And an error message should be retrievable.
        let mut msg = vec![0i8; 256];
        let n = mcgen_last_error(msg.as_mut_ptr(), msg.len());
        assert!(n > 0, "expected an error message");

        unsafe { mcgen_world_destroy(world) };
    }

    #[test]
    fn null_out_pointer_is_rejected() {
        let rc = unsafe { mcgen_world_create(1, ptr::null_mut()) };
        assert_eq!(rc, MCGEN_ERR_NULL);
    }

    #[test]
    fn destroying_null_is_a_noop() {
        unsafe { mcgen_world_destroy(ptr::null_mut()) };
    }
}

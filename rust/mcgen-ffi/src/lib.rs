/// Copy noise `index`'s registry name into `buf` as UTF-8. `out_len` receives the byte count
/// written (never including a terminator).
///
/// # Safety
/// `world` must be live; `buf` must be writable for `buf_len` bytes and `out_len` writable.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_noise_name(
    world: *const McGenWorld,
    index: u32,
    buf: *mut u8,
    buf_len: usize,
    out_len: *mut usize,
) -> i32 {
    guard("mcgen_world_noise_name", || {
        if world.is_null() || buf.is_null() || out_len.is_null() {
            set_error("world, buf or out_len was null");
            return MCGEN_ERR_NULL;
        }
        let world = unsafe { &*world };
        let Some(name) = world.noise_names.get(index as usize) else {
            set_error(format!(
                "noise index {index} out of range ({} noises)",
                world.noise_names.len()
            ));
            return MCGEN_ERR_ARG;
        };
        let bytes = name.as_bytes();
        if bytes.len() > buf_len {
            set_error(format!(
                "buffer of {buf_len} is too small for a {} byte name",
                bytes.len()
            ));
            return MCGEN_ERR_LEN;
        }
        unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), buf, bytes.len()) };
        unsafe { *out_len = bytes.len() };
        MCGEN_OK
    })
}


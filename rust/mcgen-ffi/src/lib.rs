//! `mcgen` — C ABI wrapper around [`mcgen_core`], designed to be called from a
//! JVM via Java 21+ FFM (`java.lang.foreign`) or JNI.
//!
//! # Contract for the Java side
//!
//! * Every exported function returns `0` on success. Negative values are
//!   failures; use [`mcgen_last_error`] for a message.
//! * **No function ever unwinds a panic across the boundary.** A Rust panic
//!   escaping an `extern "C"` fn aborts the process, which in a Minecraft
//!   server means killing the player's world. Each entry point wraps its body
//!   in `catch_unwind` and converts a panic into `MCGEN_ERR_PANIC`.
//! * All buffers are caller-allocated. The Rust side validates every length
//!   before writing and never trusts a pointer.
//! * Calls are **coarse**: one call fills a whole chunk region. Crossing the
//!   boundary per block would cost more than the work it offloads.

use std::ffi::c_char;
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::sync::Mutex;

use mcgen_core::density::{DensityBuilder, DensityFunction};
use mcgen_core::fnv1a_bytes;
use mcgen_core::noise::NormalNoise;
use mcgen_core::density::NoiseSpec;
use mcgen_core::terrain::{WorldGen, BLOCKS_PER_CHUNK};

/// Bump when the ABI changes shape. The Java side refuses to run on a mismatch.
pub const MCGEN_ABI_VERSION: u32 = 2;

pub const MCGEN_OK: i32 = 0;
pub const MCGEN_ERR_NULL: i32 = 1;
pub const MCGEN_ERR_LEN: i32 = 2;
pub const MCGEN_ERR_ARG: i32 = 3;
pub const MCGEN_ERR_JSON: i32 = 4;
pub const MCGEN_ERR_PANIC: i32 = -1;

/// A prepared world: a parsed density graph plus its noise instances.
///
/// Building this is comparatively expensive, so the caller creates one and
/// reuses it across many chunk fills.
pub struct McGenWorld {
    seed: u64,
    density: DensityFunction,
    noises: Vec<NormalNoise>,
    /// Registry name per entry in `noises`, in the same order.
    noise_names: Vec<String>,
}

static LAST_ERROR: Mutex<Option<String>> = Mutex::new(None);

fn set_error(msg: impl Into<String>) {
    if let Ok(mut slot) = LAST_ERROR.lock() {
        *slot = Some(msg.into());
    }
}

/// Run `body`, converting a panic into `MCGEN_ERR_PANIC` instead of aborting
/// the host process.
fn guard<F: FnOnce() -> i32>(what: &str, body: F) -> i32 {
    match catch_unwind(AssertUnwindSafe(body)) {
        Ok(code) => code,
        Err(payload) => {
            let detail = payload
                .downcast_ref::<&str>()
                .map(|s| (*s).to_owned())
                .or_else(|| payload.downcast_ref::<String>().cloned())
                .unwrap_or_else(|| "<non-string panic payload>".to_owned());
            set_error(format!("panic in {what}: {detail}"));
            MCGEN_ERR_PANIC
        }
    }
}

/// Copy a message into a caller buffer. Always writes a NUL terminator when
/// `len > 0`. Returns the number of bytes written (excluding the terminator).
unsafe fn write_cstr(msg: &str, out: *mut c_char, len: usize) -> i32 {
    if out.is_null() || len == 0 {
        return MCGEN_ERR_LEN;
    }
    let bytes = msg.as_bytes();
    let n = bytes.len().min(len - 1);
    unsafe {
        std::ptr::copy_nonoverlapping(bytes.as_ptr(), out.cast::<u8>(), n);
        *out.add(n) = 0;
    }
    n as i32
}

/// ABI version the loaded library was built with.
#[no_mangle]
pub extern "C" fn mcgen_abi_version() -> u32 {
    MCGEN_ABI_VERSION
}

/// Retrieve the message for the most recent failure.
#[no_mangle]
pub extern "C" fn mcgen_last_error(out: *mut c_char, len: usize) -> i32 {
    guard("mcgen_last_error", || {
        let msg = LAST_ERROR
            .lock()
            .ok()
            .and_then(|m| m.clone())
            .unwrap_or_else(|| "no error recorded".to_owned());
        unsafe { write_cstr(&msg, out, len) }
    })
}

/// Derive each named noise from the world seed using vanilla's mechanism: a
/// positional factory derived from the root source, then `fromHashOf(name)`.
///
/// **Remaining deviation:** vanilla's `RandomState` seeds this root source from
/// the level seed in its own way, which we do not replicate yet. So the
/// derivation *mechanism* is now correct, while the root seeding is not.
/// The real overworld router, as the oracle sees it: the `final_density` graph, the noise
/// occurrences it references, and the clamp bounds the encoding loses.
///
/// Generated by `scripts/make-fixture.sh`. The library used to build its world from a
/// hand-written demo graph, which meant the in-server benchmark was measuring a toy rather
/// than worldgen; this is the actual thing.
const FIXTURE: &str = include_str!("../fixture/overworld.txt");

fn build_world(seed: u64) -> Result<McGenWorld, String> {
    let mut density_json: Option<&str> = None;
    let mut occurrences: Vec<(i32, Vec<u64>, String)> = Vec::new();
    let mut clamps: Vec<(f64, f64)> = Vec::new();
    let mut section = "";

    for line in FIXTURE.lines() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        match line {
            "occurrences" => {
                section = "occurrences";
                continue;
            }
            "clamps" => {
                section = "clamps";
                continue;
            }
            _ => {}
        }
        if let Some(rest) = line.strip_prefix("density\t") {
            density_json = Some(rest);
            continue;
        }
        let mut parts = line.split(' ');
        match section {
            "occurrences" => {
                let first_octave = parts
                    .next()
                    .ok_or("fixture: occurrence is missing its first octave")?
                    .parse::<i32>()
                    .map_err(|e| format!("fixture: bad first octave: {e}"))?;
                let amplitudes = parts
                    .next()
                    .ok_or("fixture: occurrence is missing its amplitudes")?
                    .split(',')
                    .map(|b| {
                        u64::from_str_radix(b, 16)
                            .map_err(|e| format!("fixture: bad amplitude bits: {e}"))
                    })
                    .collect::<Result<Vec<u64>, String>>()?;
                let name = parts
                    .next()
                    .ok_or("fixture: occurrence is missing its name")?
                    .to_owned();
                occurrences.push((first_octave, amplitudes, name));
            }
            "clamps" => {
                let min = f64::from_bits(
                    u64::from_str_radix(
                        parts.next().ok_or("fixture: clamp is missing its minimum")?,
                        16,
                    )
                    .map_err(|e| format!("fixture: bad clamp minimum: {e}"))?,
                );
                let max = f64::from_bits(
                    u64::from_str_radix(
                        parts.next().ok_or("fixture: clamp is missing its maximum")?,
                        16,
                    )
                    .map_err(|e| format!("fixture: bad clamp maximum: {e}"))?,
                );
                clamps.push((min, max));
            }
            _ => {}
        }
    }

    let density_json = density_json.ok_or("fixture: no density graph")?;
    let mut builder = DensityBuilder::new();
    builder.set_world_seed(seed);
    builder.set_occurrences(occurrences);
    builder.set_clamp_bounds(clamps);
    let density = builder
        .parse_str(density_json)
        .map_err(|e| format!("failed to parse the router graph: {e}"))?;

    // The occurrences mode hands back one spec per noise occurrence, in the order the graph
    // meets them, each carrying the registry name the oracle reported. That name is what
    // `RandomState` hashes the world seed with, so it is the whole of the seeding rule.
    let mut noise_names = Vec::new();
    let noises: Vec<NormalNoise> = builder
        .noise_specs()
        .iter()
        .map(|spec| match spec {
            NoiseSpec::Seeded { name, .. } => {
                noise_names.push(name.clone());
                spec.build_seeded(seed, name)
            }
            other => panic!("occurrence mode should produce Seeded specs, got {other:?}"),
        })
        .collect();

    Ok(McGenWorld {
        seed,
        density,
        noises,
        noise_names,
    })
}


/// Create a world. On success writes the handle to `*out`.
///
/// # Safety
/// `out` must be a valid, writable pointer to a `*mut McGenWorld`.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_create(seed: u64, out: *mut *mut McGenWorld) -> i32 {
    guard("mcgen_world_create", || {
        if out.is_null() {
            set_error("mcgen_world_create: out pointer was null");
            return MCGEN_ERR_NULL;
        }
        match build_world(seed) {
            Ok(w) => {
                unsafe { *out = Box::into_raw(Box::new(w)) };
                MCGEN_OK
            }
            Err(e) => {
                set_error(e);
                MCGEN_ERR_JSON
            }
        }
    })
}

/// Destroy a world created by [`mcgen_world_create`].
///
/// # Safety
/// `world` must be a handle from `mcgen_world_create` that has not been freed.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_destroy(world: *mut McGenWorld) {
    let _ = catch_unwind(AssertUnwindSafe(|| {
        if !world.is_null() {
            drop(unsafe { Box::from_raw(world) });
        }
    }));
}

/// Validate an output buffer for an `n x n` chunk region.
fn check_region_buf(n: i32, out: *mut u8, out_len: usize) -> Option<usize> {
    if out.is_null() {
        set_error("output buffer was null");
        return None;
    }
    if n <= 0 {
        set_error(format!("chunk count must be positive, got {n}"));
        return None;
    }
    let expected = match (n as usize)
        .checked_mul(n as usize)
        .and_then(|c| c.checked_mul(BLOCKS_PER_CHUNK))
    {
        Some(e) => e,
        None => {
            set_error("region size overflowed");
            return None;
        }
    };
    if out_len != expected {
        set_error(format!(
            "output buffer is {out_len} bytes but {n}x{n} chunks needs {expected}"
        ));
        return None;
    }
    Some(expected)
}

/// Fill an `n x n` chunk region, multithreaded.
///
/// # Safety
/// `world` must be a live handle; `out` must point to at least `out_len` bytes.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_fill_region(
    world: *const McGenWorld,
    chunk_x: i32,
    chunk_z: i32,
    n: i32,
    out: *mut u8,
    out_len: usize,
) -> i32 {
    guard("mcgen_world_fill_region", || {
        if world.is_null() {
            set_error("world handle was null");
            return MCGEN_ERR_NULL;
        }
        let Some(expected) = check_region_buf(n, out, out_len) else {
            return MCGEN_ERR_LEN;
        };
        let world = unsafe { &*world };
        let buf = unsafe { std::slice::from_raw_parts_mut(out, expected) };
        let wg = WorldGen {
            density: &world.density,
            noises: &world.noises,
        };
        wg.fill_region(chunk_x, chunk_z, n, buf);
        MCGEN_OK
    })
}

/// Same as [`mcgen_world_fill_region`] but single-threaded.
///
/// Exists purely so benchmarks can show the parallel speedup without the JVM
/// side having to reimplement anything.
///
/// # Safety
/// Same requirements as `mcgen_world_fill_region`.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_fill_region_serial(
    world: *const McGenWorld,
    chunk_x: i32,
    chunk_z: i32,
    n: i32,
    out: *mut u8,
    out_len: usize,
) -> i32 {
    guard("mcgen_world_fill_region_serial", || {
        if world.is_null() {
            set_error("world handle was null");
            return MCGEN_ERR_NULL;
        }
        let Some(expected) = check_region_buf(n, out, out_len) else {
            return MCGEN_ERR_LEN;
        };
        let world = unsafe { &*world };
        let buf = unsafe { std::slice::from_raw_parts_mut(out, expected) };
        let wg = WorldGen {
            density: &world.density,
            noises: &world.noises,
        };
        let mut single = vec![0u8; BLOCKS_PER_CHUNK];
        for i in 0..(n * n) {
            wg.fill_chunk_chunked(chunk_x + (i % n), chunk_z + (i / n), &mut single);
            let off = i as usize * BLOCKS_PER_CHUNK;
            buf[off..off + BLOCKS_PER_CHUNK].copy_from_slice(&single);
        }
        MCGEN_OK
    })
}

/// FNV-1a hash of a generated region. Cheap way to check that two runs (or two
/// languages) produced identical terrain.
///
/// # Safety
/// `world` must be a live handle.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_fingerprint(
    world: *const McGenWorld,
    chunk_x: i32,
    chunk_z: i32,
    n: i32,
    out_hash: *mut u64,
) -> i32 {
    guard("mcgen_world_fingerprint", || {
        if world.is_null() || out_hash.is_null() {
            set_error("world or out_hash was null");
            return MCGEN_ERR_NULL;
        }
        if n <= 0 {
            set_error(format!("chunk count must be positive, got {n}"));
            return MCGEN_ERR_ARG;
        }
        let world = unsafe { &*world };
        let wg = WorldGen {
            density: &world.density,
            noises: &world.noises,
        };
        let total = (n as usize) * (n as usize) * BLOCKS_PER_CHUNK;
        let mut buf = vec![0u8; total];
        wg.fill_region(chunk_x, chunk_z, n, &mut buf);
        unsafe { *out_hash = fnv1a_bytes(&buf) };
        MCGEN_OK
    })
}

/// Raw noise throughput: sample a noise `count` times and return the sum.
///
/// The sum is returned so the optimiser cannot delete the loop; the caller
/// times the call to get samples/second.
///
/// # Safety
/// `world` must be a live handle; `out_sum` must be writable.
#[no_mangle]
pub unsafe extern "C" fn mcgen_world_noise_samples(
    world: *const McGenWorld,
    count: u64,
    out_sum: *mut f64,
) -> i32 {
    guard("mcgen_world_noise_samples", || {
        if world.is_null() || out_sum.is_null() {
            set_error("world or out_sum was null");
            return MCGEN_ERR_NULL;
        }
        let world = unsafe { &*world };
        if world.noises.is_empty() {
            set_error("world has no noise instances");
            return MCGEN_ERR_ARG;
        }
        let noise = &world.noises[0];
        let mut sum = 0.0f64;
        for i in 0..count {
            let t = i as f64;
            sum += noise.get(t * 0.11, t * 0.07, -t * 0.05);
        }
        unsafe { *out_sum = sum };
        MCGEN_OK
    })
}

